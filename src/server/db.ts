import pg from 'pg';
import { config } from './config';
import type { EventRow, EventStats, GuestRow } from '../shared/types';

// Postgres. Los tipos se ajustan para que el resto de la app reciba lo mismo que antes:
// conteos como número y fechas como texto ISO.
pg.types.setTypeParser(20, (v) => Number(v)); // int8 (COUNT)
pg.types.setTypeParser(1184, (v) => new Date(v).toISOString()); // timestamptz

export const pool = new pg.Pool({ connectionString: config.databaseUrl, max: 10 });

type Conn = pg.Pool | pg.PoolClient;

export async function query<T = Record<string, unknown>>(sql: string, params: unknown[] = [], conn: Conn = pool): Promise<T[]> {
  return (await conn.query(sql, params)).rows as T[];
}

export async function one<T = Record<string, unknown>>(sql: string, params: unknown[] = [], conn: Conn = pool): Promise<T | undefined> {
  return (await query<T>(sql, params, conn))[0];
}

/** Ejecuta y devuelve cuántas filas cambió. */
export async function exec(sql: string, params: unknown[] = [], conn: Conn = pool): Promise<number> {
  return (await conn.query(sql, params)).rowCount ?? 0;
}

export async function tx<T>(fn: (c: pg.PoolClient) => Promise<T>): Promise<T> {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await fn(client);
    await client.query('COMMIT');
    return result;
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
  }
}

