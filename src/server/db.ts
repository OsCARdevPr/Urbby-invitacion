/** Crea o actualiza las tablas. Un candado evita que dos procesos migren a la vez. */
export async function initDb() {
  await tx(async (c) => {
    await c.query('SELECT pg_advisory_xact_lock(724119)');
    await c.query('CREATE TABLE IF NOT EXISTS schema_migrations (version integer PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now())');
    const done = new Set((await query<{ version: number }>('SELECT version FROM schema_migrations', [], c)).map((r) => r.version));
    for (let v = 0; v < migrations.length; v++) {
      if (done.has(v + 1)) continue;
      await c.query(migrations[v]);
      await c.query('INSERT INTO schema_migrations (version) VALUES ($1)', [v + 1]);
    }
  });
}

export const nowIso = () => new Date().toISOString();

export async function kvGet<T>(key: string, fallback: T): Promise<T> {
  const row = await one<{ value: T }>('SELECT value FROM kv WHERE key = $1', [key]);
  return row ? { ...fallback, ...row.value } : fallback;
}

export async function kvSet(key: string, value: unknown) {
  await exec('INSERT INTO kv (key, value) VALUES ($1, $2) ON CONFLICT (key) DO UPDATE SET value = excluded.value', [key, JSON.stringify(value)]);
}

// ── Consultas compartidas ────────────────────────────────────────

export const getEvent = (id: number) => one<EventRow>('SELECT * FROM events WHERE id = $1', [id]);

export const getGuest = (id: number) => one<GuestRow>('SELECT * FROM guests WHERE id = $1', [id]);

export const getGuestByToken = (token: string) => one<GuestRow>('SELECT * FROM guests WHERE token = $1', [token]);

export const listGuests = (eventId: number) =>
  query<GuestRow>('SELECT * FROM guests WHERE event_id = $1 ORDER BY lower(name), id', [eventId]);

export async function eventStats(eventId: number): Promise<EventStats> {
  const row = await one<EventStats>(
    `SELECT
       count(*)                                                                 AS "total",
       count(*) FILTER (WHERE email_status = 'sent')                            AS "emailSent",
       count(*) FILTER (WHERE email_status = 'failed')                          AS "emailFailed",
       count(*) FILTER (WHERE wa_status = 'queued')                             AS "waQueued",
       count(*) FILTER (WHERE wa_status IN ('sent','delivered','read'))         AS "waSent",
       count(*) FILTER (WHERE wa_status IN ('delivered','read'))                AS "waDelivered",
       count(*) FILTER (WHERE wa_status = 'read')                               AS "waRead",
       count(*) FILTER (WHERE wa_status IN ('failed','no_whatsapp','uncertain')) AS "waProblems",
       count(*) FILTER (WHERE checked_in_at IS NOT NULL)                        AS "checkedIn"
     FROM guests WHERE event_id = $1`,
    [eventId],
  );
  return row!;
}
